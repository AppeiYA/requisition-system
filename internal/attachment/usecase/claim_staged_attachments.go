package usecase

import (
	"context"
	"errors"
	"time"

	"github.com/AppeiYA/requisition-system/internal/attachment/domain"
	attachmentin "github.com/AppeiYA/requisition-system/internal/attachment/ports/in"
	attachmentout "github.com/AppeiYA/requisition-system/internal/attachment/ports/out"
	customerrors "github.com/AppeiYA/requisition-system/internal/shared/infrastructure/errors"
)

// ErrStagedUploadUnavailable deliberately hides why a token cannot be used:
// malformed, foreign, expired and already-claimed tokens all look the same to
// the client. The caller is the requisition creation transaction, so returning
// this error rolls the whole creation back.
var ErrStagedUploadUnavailable = customerrors.NewBadRequestError("one or more uploads are invalid, expired or already used")

var _ attachmentin.ClaimStagedAttachmentsUsecaseInt = (*ClaimStagedAttachmentsUsecase)(nil)

// ClaimStagedAttachmentsUsecase turns staged uploads into pending attachment
// metadata plus outbox rows. It never touches file bytes and assumes the
// caller's context already carries the transaction opened by requisition
// creation.
type ClaimStagedAttachmentsUsecase struct {
	stagedRepo     attachmentout.StagedUploadRepository
	attachmentRepo attachmentout.AttachmentRepository
	outboxRepo     attachmentout.ReconciliationOutboxRepository
	idGen          attachmentout.IDGenerator
	maxPerRef      int
	now            func() time.Time
}

func NewClaimStagedAttachmentsUsecase(
	stagedRepo attachmentout.StagedUploadRepository,
	attachmentRepo attachmentout.AttachmentRepository,
	outboxRepo attachmentout.ReconciliationOutboxRepository,
	idGen attachmentout.IDGenerator,
	maxPerRef ...int,
) *ClaimStagedAttachmentsUsecase {
	limit := 0
	if len(maxPerRef) > 0 && maxPerRef[0] > 0 {
		limit = maxPerRef[0]
	}
	return &ClaimStagedAttachmentsUsecase{
		stagedRepo:     stagedRepo,
		attachmentRepo: attachmentRepo,
		outboxRepo:     outboxRepo,
		idGen:          idGen,
		maxPerRef:      limit,
		now:            func() time.Time { return time.Now().UTC() },
	}
}

func (uc *ClaimStagedAttachmentsUsecase) Claim(
	ctx context.Context,
	targets []attachmentin.ClaimStagedAttachmentTarget,
) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if len(targets) == 0 {
		return nil
	}

	actorID := ""
	seen := make(map[string]struct{}, len(targets))
	ids := make([]string, 0, len(targets))
	refs := make(map[string]*domain.AttachmentRef, len(targets))
	refCounts := make(map[string]int)
	for _, target := range targets {
		if target.ActorID == "" || !domain.IsValidStagedUploadID(target.StagedUploadID) {
			return ErrStagedUploadUnavailable
		}
		if actorID == "" {
			actorID = target.ActorID
		} else if target.ActorID != actorID {
			return ErrStagedUploadUnavailable
		}
		if _, duplicate := seen[target.StagedUploadID]; duplicate {
			return ErrStagedUploadUnavailable
		}
		seen[target.StagedUploadID] = struct{}{}

		ref, err := domain.NewAttachmentRef(domain.AttachmentRefName(target.RefName), target.RefID)
		if err != nil {
			// Parent IDs are generated by the server; a mismatch is a
			// programming error and must not be disguised as a client error.
			return err
		}
		refKey := ref.RefName().String() + ":" + ref.ID()
		refCounts[refKey]++
		if uc.maxPerRef > 0 && refCounts[refKey] > uc.maxPerRef {
			return ErrAttachmentLimitReached
		}
		refs[target.StagedUploadID] = ref
		ids = append(ids, target.StagedUploadID)
	}

	now := uc.now()
	uploads, err := uc.stagedRepo.ClaimByIDs(ctx, ids, actorID, now)
	if err != nil {
		return err
	}
	if len(uploads) != len(ids) {
		return ErrStagedUploadUnavailable
	}
	claimed := make(map[string]*domain.StagedUpload, len(uploads))
	for _, upload := range uploads {
		claimed[upload.ID()] = upload
	}

	for _, target := range targets {
		upload, ok := claimed[target.StagedUploadID]
		if !ok {
			return ErrStagedUploadUnavailable
		}
		ref := refs[target.StagedUploadID]

		attachmentID, err := uc.idGen.GenerateID(domain.AttachmentIDPrefix)
		if err != nil {
			return err
		}
		key, err := domain.NewAttachmentKey(ref, attachmentID)
		if err != nil {
			return err
		}
		pending, err := domain.NewPendingAttachment(
			attachmentID,
			ref,
			upload.ID(),
			key,
			upload.OriginalFileName(),
			upload.ContentType(),
			upload.FileSize(),
			upload.Checksum(),
			upload.UploadedBy(),
		)
		if err != nil {
			return err
		}
		if err := uc.attachmentRepo.Save(ctx, pending); err != nil {
			return normaliseClaimError(err)
		}

		eventID, err := uc.idGen.GenerateID(domain.ReconciliationEventIDPrefix)
		if err != nil {
			return err
		}
		event, err := domain.NewReconciliationEvent(
			eventID, pending.ID(), upload.ID(),
			upload.StoragePath(), key, upload.Checksum(), now,
		)
		if err != nil {
			return err
		}
		if err := uc.outboxRepo.Save(ctx, event); err != nil {
			return normaliseClaimError(err)
		}
	}
	return nil
}

// normaliseClaimError converts the unique-constraint conflicts that protect
// against double claims into the same client-facing error as a missing token.
func normaliseClaimError(err error) error {
	if errors.Is(err, attachmentout.ErrAttachmentExists) ||
		errors.Is(err, attachmentout.ErrReconciliationEventExists) ||
		errors.Is(err, attachmentout.ErrStagedUploadClaimConflict) {
		return ErrStagedUploadUnavailable
	}
	return err
}
